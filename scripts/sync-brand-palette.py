"""Emit shared CSS from the palette also used by the PDF generator."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
colors=json.loads((root/'lib/brand/palette.json').read_text())
css='/* Generated by scripts/sync-brand-palette.py. Edit lib/brand/palette.json. */\n:root {\n'
css+=''.join(f'  --brand-{name}: {value};\n' for name,value in colors.items())+'}\n'
(root/'app/radr-palette.css').write_text(css)
def luminance(value):
 channels=[int(value[i:i+2],16)/255 for i in (1,3,5)]
 linear=[v/12.92 if v<=.04045 else ((v+.055)/1.055)**2.4 for v in channels]
 return sum(a*b for a,b in zip(linear,[.2126,.7152,.0722]))
for foreground,background in [('ink','jade'),('sapphire','canvas'),('ocean','canvas'),('jade-ink','jade-soft'),('muted','canvas')]:
 a,b=sorted([luminance(colors[foreground]),luminance(colors[background])]);ratio=(b+.05)/(a+.05)
 assert ratio>=4.5,(foreground,background,ratio)
 print(f'{foreground} on {background}: {ratio:.2f}:1')
